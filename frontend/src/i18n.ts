const TEXTS: Record<string, Texts> = { en, ru };

/** Return a translator for `language`, filling `{placeholders}`. */
export function translator(
  language: string,
): (key: TextKey, values?: Record<string, string | number>) => string {
  const texts = TEXTS[language.split("-")[0] ?? "en"] ?? en;
  return (key, values) =>
    texts[key].replace(/\{(\w+)\}/g, (match, name: string) =>
      values && name in values ? String(values[name]) : match,
    );
}

/** The text key for an operation method or action, falling back to "other". */
export function methodKey(method: string): TextKey {
  const key = `method_${method}`;
  return key in en ? (key as TextKey) : "method_other";
}

export function actionKey(action: string): TextKey {
  const key = `action_${action}`;
  return key in en ? (key as TextKey) : "action_other";
}
